#!/usr/bin/env python3
"""Verify/package one pinned compiler product; never compile or execute a shader.

The manifest digest is an explicit review boundary. Updating payload hashes in
the manifest alone cannot admit a new shader under the existing product class.
"""

import argparse
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import shutil
import stat
import subprocess
import sys
import tempfile

PRODUCT_CLASS = "AppleAddOneGfx1100V1"
MANIFEST_SHA256 = "54c5e0d812ce5623577c03fcf47f1d4dac65eb09eeb73ac03b7acae6613be92b"
CODE_SHA256 = "ac333acf99387a4063fae75a89dd4e6968907f6b78702d26442dd8a3575f7dda"
SPIRV_SHA256 = "dc617a376ba9594f26dfb3b07656ef4a87236c5fb1ff387b02d0fdb8a59e2439"
DEFAULT_FIXTURE = Path(__file__).resolve().parent / "fixtures/apple-add-one"
HEADER = "shader_data.hpp"


class VerificationError(ValueError):
    pass


def require(condition, message):
    if not condition:
        raise VerificationError(message)


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def read_regular(root, name):
    relative = PurePosixPath(name)
    require(not relative.is_absolute() and relative.parts and
            all(part not in (".", "..") and ":" not in part and "\\" not in part
                for part in relative.parts), "unsafe fixture path: " + name)
    path = root
    for part in relative.parts:
        path = path / part
        require(not path.is_symlink(), "symlink in fixture path: " + name)
    require(path.is_file() and stat.S_ISREG(path.stat().st_mode),
            "missing/nonregular fixture file: " + name)
    require(path.stat().st_size <= 2 * 1024 * 1024, "fixture file exceeds 2 MiB: " + name)
    return path.read_bytes()


def parse_json(data, name):
    def unique_keys(pairs):
        result = {}
        for key, value in pairs:
            require(key not in result, "duplicate JSON key in " + name + ": " + key)
            result[key] = value
        return result
    try:
        return json.loads(data.decode("utf-8"), object_pairs_hook=unique_keys)
    except (UnicodeError, json.JSONDecodeError) as error:
        raise VerificationError("invalid JSON in " + name + ": " + str(error)) from error


def render_header(code):
    require(len(code) == 104 and sha256(code) == CODE_SHA256,
            "refusing to pack replacement shader bytes")
    rows = ["    " + ", ".join("0x%02x" % byte for byte in code[offset:offset + 12]) + ","
            for offset in range(0, len(code), 12)]
    return ("// SPDX-License-Identifier: MIT\n"
            "// Generated by userspace/compiler/verify_fixture.py --write-header.\n"
            "// Exact pinned compiler output, including all ACO padding; no GPU execution claim.\n"
            "#pragma once\n\n#include <stddef.h>\n#include <stdint.h>\n\n"
            "namespace hackynavi { namespace gfxaco { namespace fixture {\n"
            'static constexpr char kProductClass[] = "' + PRODUCT_CLASS + '";\n'
            'static constexpr char kCodeSha256[] = "' + CODE_SHA256 + '";\n'
            "static constexpr size_t kCodeBytes = 104;\n"
            "static constexpr size_t kExecutableBytes = 84;\n"
            "static constexpr size_t kCodeAlignment = 256;\n"
            "static constexpr uint8_t kCode[kCodeBytes] = {\n" + "\n".join(rows) + "\n};\n"
            'static_assert(sizeof(kCode) == kCodeBytes, "complete ACO code bytes");\n'
            "} } } // namespace hackynavi::gfxaco::fixture\n").encode("utf-8")


def verify(root, check_header=True):
    root = Path(root).resolve()
    manifest_bytes = read_regular(root, "manifest.json")
    require(sha256(manifest_bytes) == MANIFEST_SHA256, "manifest SHA-256 differs from pinned product")
    manifest = parse_json(manifest_bytes, "manifest.json")
    require(manifest["schema_version"] == 1 and manifest["product_class"] == PRODUCT_CLASS,
            "fixture product/schema mismatch")
    require(manifest["hardware_executed"] is False, "fixture must not claim GPU execution")
    expected_paths = set(manifest["files"]) | {"manifest.json"}
    actual_paths = {path.relative_to(root).as_posix() for path in root.rglob("*")
                    if path.is_file() or path.is_symlink()}
    allowed_missing = set() if check_header else {HEADER}
    require(actual_paths <= expected_paths and expected_paths - actual_paths <= allowed_missing,
            "fixture inventory mismatch: missing=" + str(sorted(expected_paths - actual_paths)) +
            " unexpected=" + str(sorted(actual_paths - expected_paths)))
    payloads = {}
    for name, record in manifest["files"].items():
        if name == HEADER and not check_header:
            continue
        data = read_regular(root, name)
        require(len(data) == record["bytes"], "size mismatch: " + name)
        require(sha256(data) == record["sha256"], "SHA-256 mismatch: " + name)
        payloads[name] = data

    config = parse_json(payloads["shader.json"], "shader.json")
    require(config == manifest["launch_metadata"], "launch metadata mismatch")
    require(config["target"] == "gfx1100" and config["wave_size"] == 32 and
            config["workgroup_size"] == [64, 1, 1] and config["code_bytes"] == 104 and
            config["executable_bytes"] == 84 and config["code_alignment"] == 256,
            "fixed code/target/workgroup contract mismatch")
    require(config["user_sgprs"] == {"descriptor_table_gpu_va": [0, 1],
                                     "push_constants_gpu_va": [2, 3]} and
            config["descriptor_binding_mask"] == 3 and config["descriptor_set"] == 0 and
            config["descriptor_stride_bytes"] == 16 and config["push_constant_bytes"] == 48,
            "descriptor/push-constant ABI mismatch")
    require([config["compute_pgm_rsrc1"], config["compute_pgm_rsrc2"],
             config["compute_pgm_rsrc3"]] == [539754498, 1928, 0] and
            config["dispatch_initiator_required_bits"] == 32768 and
            config["system_sgprs"] == {"workgroup_x": 4, "workgroup_y": 5,
                                       "workgroup_z": 6, "tg_size": 7} and
            config["system_vgprs"] == {"packed_local_invocation_id": 0},
            "fixed resource-register/system-input contract mismatch")
    require(config["scratch_bytes_per_wave"] == 0 and config["lds_bytes"] == 0 and
            config["spilled_sgprs"] == 0 and config["spilled_vgprs"] == 0 and
            config["relocations"] == [] and config["constants_bytes"] == 0,
            "unsupported shader resource requirement")

    provenance = parse_json(payloads["provenance.json"], "provenance.json")
    require(provenance["input_sha256"] == sha256(payloads["translated/shader.spv"]) == SPIRV_SHA256,
            "SPIR-V input provenance mismatch")
    require(provenance["shader_sha256"] == sha256(payloads["shader.bin"]) == CODE_SHA256 and
            provenance["hardware_executed"] is False, "shader provenance mismatch")
    require(provenance["spirv_entry_point"] == "main" and
            provenance["local_size_specialization"] == {"0": 64, "1": 1, "2": 1},
            "entry/specialization provenance mismatch")
    for tool in ("compiler", "validator"):
        require(provenance[tool + "_sha256"] == manifest["tools"][tool]["sha256"],
                "tool provenance mismatch: " + tool)
    require(config["mesa_commit"] == manifest["mesa"]["commit"], "Mesa revision mismatch")

    module = parse_json(payloads["translated/module.json"], "translated/module.json")
    require(module == {"abi_version": 1, "metal_entry_point": "add_one",
                       "spirv_entry_point": "main", "target_environment": "vulkan1.2"},
            "translated module contract mismatch")
    reflection = parse_json(payloads["translated/reflection.json"], "translated/reflection.json")
    require(reflection["reflection_version"] == 56 and reflection["entry_point"] == "add_one" and
            reflection["stage"] == "Kernel" and reflection["local_size"] == [64, 1, 1] and
            reflection["kernel_dispatch"] == {"ThreadsDynamic": {"offset": 0}},
            "Metal reflection dispatch mismatch")
    require(len(reflection["bindings"]) == 2, "Metal reflection binding count mismatch")
    for index, binding in enumerate(reflection["bindings"]):
        require(binding["kind"] == "Buffer" and binding["metal_index"] == index and
                binding["descriptor"] == {"set": 0, "binding": index, "count": 1} and
                binding["access"] == ("ReadOnly" if index == 0 else "WriteOnly") and
                binding["type_name"] == "uint", "Metal reflection buffer mismatch")

    apple = parse_json(payloads["source/apple/provenance.json"], "source/apple/provenance.json")
    require(apple["capture"]["files"]["add_one.air"]["sha256"] ==
            sha256(payloads["source/apple/add_one.air"]), "Apple AIR provenance mismatch")
    require(apple["capture"]["source_sha256"]["add_one.metal"] ==
            sha256(payloads["source/add_one.metal"]), "authored MSL provenance mismatch")
    require(apple["reader_validation"]["spirv_equivalence"]["apple_reader_spirv_sha256"] == SPIRV_SHA256,
            "Apple AIR translation provenance mismatch")
    header = render_header(payloads["shader.bin"])
    record = manifest["files"][HEADER]
    require(len(header) == record["bytes"] and sha256(header) == record["sha256"],
            "generated header differs from pinned manifest")
    if check_header:
        require(payloads[HEADER] == header, "generated header is stale or changed")
    return manifest, header


def write_header(root):
    root = Path(root).resolve()
    manifest, header = verify(root, check_header=False)
    # Validation completes before creating or replacing any output.
    descriptor, temporary = tempfile.mkstemp(prefix=".shader_data-", suffix=".tmp", dir=root)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(header)
        os.replace(temporary, root / HEADER)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)
    verify(root)
    return manifest


def self_test(root):
    verify(root)
    checks = []
    mutations = [
        ("altered-binary", "shader.bin", lambda data: bytes([data[0] ^ 1]) + data[1:]),
        ("altered-metadata", "shader.json", lambda data: data.replace(b'"wave_size": 32', b'"wave_size": 64')),
        ("altered-reflection", "translated/reflection.json", lambda data: data.replace(b'"ReadOnly"', b'"WriteOnly"')),
        ("altered-input", "translated/shader.spv", lambda data: data[:-1] + bytes([data[-1] ^ 1])),
        ("altered-air", "source/apple/add_one.air", lambda data: data[:-1]),
        ("altered-manifest-hash", "manifest.json", lambda data: data.replace(CODE_SHA256.encode(), b"0" * 64)),
        ("altered-header", HEADER, lambda data: data.replace(b"0x", b"0X", 1)),
        ("missing-binary", "shader.bin", None),
        ("missing-metadata", "shader.json", None),
        ("missing-reflection", "translated/reflection.json", None),
    ]
    with tempfile.TemporaryDirectory(prefix="hackynavi-fixture-check-") as scratch:
        temporary_root = Path(scratch)
        for label, name, mutate in mutations:
            trial = temporary_root / label
            shutil.copytree(root, trial)
            path = trial / name
            before = path.read_bytes()
            if mutate is None:
                path.unlink()
            else:
                after = mutate(before)
                require(after != before, "ineffective negative test: " + label)
                path.write_bytes(after)
            try:
                verify(trial)
            except VerificationError:
                checks.append(label)
            else:
                raise VerificationError("accepted negative test: " + label)

        trial = temporary_root / "refuse-output-after-failure"
        shutil.copytree(root, trial)
        (trial / "shader.bin").write_bytes(b"not a replacement shader")
        old_header = (trial / HEADER).read_bytes()
        result = subprocess.run([sys.executable, str(Path(__file__).resolve()), "--fixture", str(trial),
                                 "--write-header"], capture_output=True, text=True, timeout=30)
        response = json.loads(result.stdout)
        require(result.returncode != 0 and response["status"] == "failed" and
                response["hardware_executed"] is False and (trial / HEADER).read_bytes() == old_header,
                "failed input produced misleading success or changed header")
        checks.append("CLI-failure-preserves-header")
        (trial / HEADER).unlink()
        try:
            write_header(trial)
        except VerificationError:
            require(not (trial / HEADER).exists(), "failed input published a header")
        else:
            raise VerificationError("packer accepted invalid input")
        checks.append("failure-publishes-no-header")

        trial = temporary_root / "reproduce-header"
        shutil.copytree(root, trial)
        expected = (trial / HEADER).read_bytes()
        (trial / HEADER).unlink()
        write_header(trial)
        require((trial / HEADER).read_bytes() == expected, "header regeneration is nondeterministic")
        checks.append("exact-header-regeneration")
    return checks


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fixture", type=Path, default=DEFAULT_FIXTURE)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="verify all files and exact generated header (default)")
    mode.add_argument("--write-header", action="store_true", help="reproduce header from verified fixed shader bytes")
    mode.add_argument("--self-test", action="store_true", help="run isolated positive and rejection tests")
    args = parser.parse_args()
    try:
        checks = self_test(args.fixture) if args.self_test else None
        if args.write_header:
            manifest = write_header(args.fixture)
        else:
            manifest, _ = verify(args.fixture)
        report = {"status": "verified", "product_class": PRODUCT_CLASS,
                  "manifest_sha256": MANIFEST_SHA256, "shader_sha256": CODE_SHA256,
                  "code_bytes": 104, "executable_bytes": 84,
                  "verified_files": len(manifest["files"]), "hardware_executed": False}
        if checks is not None:
            report["self_tests"] = checks
        print(json.dumps(report, indent=2))
        return 0
    except (VerificationError, OSError, KeyError, TypeError, subprocess.SubprocessError) as error:
        print(json.dumps({"status": "failed", "error": str(error), "hardware_executed": False}, indent=2))
        return 1


if __name__ == "__main__":
    sys.exit(main())
