"""Embed pinned, unmodified AMD binary firmware; never download or run it."""
import argparse
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "firmware" / "manifest.json"
MAX_RESOURCE_BYTES = 4 * 1024 * 1024
RESOURCE_IDS = ("PspSos", "Sdma", "Smu", "GcPfp", "GcMe", "GcMec", "GcImu", "GcRlc", "Dmcub", "PspTa")


def checked_resource(directory, item):
    """Check bounds and provenance before exposing any firmware bytes."""
    path = PurePosixPath(item["path"])
    if (path.is_absolute() or not path.parts or ".." in path.parts or
            "\\" in item["path"] or ":" in item["path"]):
        raise ValueError("Firmware manifest contains an invalid relative path")
    count = item["bytes"]
    if type(count) is not int or not 0 < count <= MAX_RESOURCE_BYTES:
        raise ValueError("Firmware manifest contains an invalid resource size")
    if not re.fullmatch(r"[0-9a-f]{64}", item["sha256"]):
        raise ValueError("Firmware manifest contains an invalid SHA256")
    source = directory.joinpath(*path.parts)
    # A bounded read also detects growth/shrinkage between stat and read.
    if source.stat().st_size != count:
        raise ValueError(f"Wrong resource size: {source}")
    with source.open("rb") as stream:
        data = stream.read(count + 1)
    if len(data) != count or hashlib.sha256(data).hexdigest() != item["sha256"]:
        raise ValueError(f"Resource does not match pinned SHA256: {source}")
    return data


def render_source(records):
    lines = [
        "// Generated by scripts/embed-firmware.py; do not edit.",
        "// AMD firmware bytes retain their separate LICENSE.amdgpu terms.",
        '#include "hackynavi/firmware_resources.hpp"',
        "namespace hackynavi {", "namespace {",
    ]
    for item, data in records:
        lines.append(f'alignas(16) const uint8_t k{item["id"]}[] = {{')
        for start in range(0, len(data), 16):
            lines.append("    " + ",".join(f"0x{value:02x}" for value in data[start:start + 16]) + ",")
        lines.append("};")
    lines += ["}", "bool getFirmwareResource(FirmwareResourceId id, FirmwareResource& out) {",
              "    out = FirmwareResource{};", "    switch (id) {"]
    for item, _ in records:
        name = item["id"]
        lines += [f"    case FirmwareResourceId::{name}:",
                  f'        out = {{k{name}, sizeof(k{name}), {json.dumps(item["path"])},',
                  f'               {json.dumps(item["sha256"])}}};', "        return true;"]
    lines += ["    }", "    return false;", "}", "}", ""]
    return "\n".join(lines).encode("ascii")


def replace_file(path, data):
    # No truncated generated source is visible if writing is interrupted.
    descriptor, temporary = tempfile.mkstemp(prefix=path.name + ".", dir=path.parent)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(data)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def generate(input_dir, output_dir):
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    if (manifest["schema_version"] != 1 or
            tuple(item["id"] for item in manifest["files"]) != RESOURCE_IDS):
        raise ValueError("Firmware resource IDs do not match the compiled interface")
    # Validate ALL files and license before changing ANY build output.
    records = [(item, checked_resource(input_dir, item)) for item in manifest["files"]]
    license_bytes = checked_resource(input_dir, manifest["license"])
    source = render_source(records)
    output_dir.mkdir(parents=True, exist_ok=True)
    replace_file(output_dir / "FirmwareResources.cpp", source)
    replace_file(output_dir / "LICENSE.amdgpu", license_bytes)
    replace_file(output_dir / "FirmwareManifest.json",
                 (json.dumps(manifest, indent=2) + "\n").encode("utf-8"))
    return sum(len(data) for _, data in records)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input-dir", type=Path, default=ROOT / ".research" / "firmware",
                        help="linux-firmware root containing the pinned files and license")
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    count = generate(args.input_dir.resolve(), args.output_dir.resolve())
    print(f"Verified and embedded {count} AMD firmware bytes in {args.output_dir}")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"Firmware embedding failed: {error}", file=sys.stderr)
        sys.exit(1)
